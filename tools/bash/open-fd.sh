#!/bin/bash

################################################################################
open_log() {
	exec 30<> $PWD/tmp.log
}

write_log() {
	echo "$@" >&30
}

close_log() {
	exec 30>&-
}

################################################################################
redirect_std() {
	exec 100<&1 101<&2
	exec 1>tmp.log 2>&1
}

stop_redirect_std() {
	exec 1<&100 2<&101
	exec 100>&- 101>&-
}

################################################################################
open_log
write_log "L: Hello World"
close_log

echo -------------------------
cat tmp.log

################################################################################
redirect_std
echo "R: Hello World"
stop_redirect_std

echo -------------------------
cat tmp.log
