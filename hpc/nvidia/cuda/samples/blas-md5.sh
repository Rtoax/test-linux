for x in $(seq 100 100 1000)
do
	suffix=bin
	[[ ${TXT} ]] && suffix=log

	prefix=blas-k${x}_m${x}_n${x}

	# Test for initial parameters
	./blas ${TXT:+-T} -O ${prefix}-i2a2b2.${suffix} -k $x -m $x -n $x \
		--init-val 2 --alpha 2 --beta 2

	# Test default increment matrix parameters
	./blas ${TXT:+-T} -O ${prefix}-iab.${suffix} -k $x -m $x -n $x
done

check_md5() {
	local md5_file=( ${@} )

	for ((i = 0; i < $(( ${#md5_file[@]} / 2 )); i++))
	do
		md5_correct=${md5_file[ $(( $i * 2 )) ]}
		file=${md5_file[ $(( $i * 2 + 1 )) ]}

		md5_real=$(fmd5 ${file})

		if [[ ${md5_correct} != ${md5_real} ]]; then
			printf "\033[31mFAILED\t%s\t%s != %s\033[m\n" $file $md5_correct $md5_real
		else
			printf "\033[32mSUCCESS\t%s\t%s\033[m\n" $file $md5_correct
		fi
	done
}

if [[ ${TXT} ]]; then
	check_md5 ${DATAS_MD5_FILE_TXT[@]}
else
	check_md5 ${DATAS_MD5_FILE_BIN[@]}
fi
