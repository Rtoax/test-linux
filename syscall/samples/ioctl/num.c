#include <stdio.h>
#include <sys/mount.h>
#include <scsi/scsi.h>
#include <scsi/sg.h>
#include <scsi/scsi_ioctl.h>
#include <linux/blkpg.h>
#include <linux/blkzoned.h>
#include <linux/cdrom.h>
#include <linux/fs.h>
#include <linux/fiemap.h>
#include <linux/nvme_ioctl.h>
#include <linux/blktrace_api.h>

#define ARRAY_SIZE(arr) (sizeof(arr) / sizeof(arr[0]))

const static char *ascii[] = {
	"\033[1;32m",
	"\033[1;33m",
};
static const char *reset = "\033[m";
static int ascii_idx = 0;
#define seperator() printf("%s%s", reset, ascii[ascii_idx++ % ARRAY_SIZE(ascii)])
#define reset() printf("%s", reset)

int main(void)
{
#define V32(b)	printf("%32s 0x%016x\n", #b, b);
#define V64(b)	printf("%32s 0x%016lx\n", #b, b);

	seperator();

	V32(TCGETS);
	V32(TCSETS);

	seperator();

	V32(CDROMPAUSE);
	V32(CDROMRESUME);
	V32(CDROMPLAYMSF);
	V32(CDROMPLAYTRKIND);
	V32(CDROMREADTOCHDR);
	V32(CDROMREADTOCENTRY);
	V32(CDROMSTOP);
	V32(CDROMSTART);
	V32(CDROMEJECT);
	V32(CDROMVOLCTRL);
	V32(CDROMSUBCHNL);
	V32(CDROMREADMODE2);
	V32(CDROMREADMODE1);
	V32(CDROMREADAUDIO);
	V32(CDROMEJECT_SW);
	V32(CDROMMULTISESSION);
	V32(CDROM_GET_MCN);
	V32(CDROM_GET_UPC);
	V32(CDROMRESET);
	V32(CDROMVOLREAD);
	V32(CDROMREADRAW);
	V32(CDROMREADCOOKED);
	V32(CDROMSEEK);
	V32(CDROMPLAYBLK);
	V32(CDROMREADALL);

	seperator();

	V32(BLKROSET);
	V32(BLKROGET);
	V32(BLKRRPART);
	V32(BLKGETSIZE);
	V32(BLKFLSBUF);
	V32(BLKRASET);
	V32(BLKRAGET);
	V32(BLKFRASET);
	V32(BLKFRAGET);
	V32(BLKSECTSET);
	V32(BLKSECTGET);
	V32(BLKSSZGET);
	V32(BLKPG);
	V64(BLKBSZGET);
	V64(BLKBSZSET);
	V64(BLKGETSIZE64);

	seperator();

	V64(BLKTRACESETUP);
	V32(BLKTRACESTART);
	V32(BLKTRACESTOP);
	V32(BLKTRACETEARDOWN);
	V32(BLKDISCARD);
	V32(BLKIOMIN);
	V32(BLKIOOPT);
	V32(BLKALIGNOFF);
	V32(BLKPBSZGET);
	V32(BLKDISCARDZEROES);
	V32(BLKSECDISCARD);
	V32(BLKROTATIONAL);
	V32(BLKZEROOUT);
#ifdef BLKGETDISKSEQ
	V64(BLKGETDISKSEQ);
#endif

	seperator();

	V64(BLKREPORTZONE);
	V64(BLKRESETZONE);
#ifdef BLKGETZONESZ
	V64(BLKGETZONESZ);
#endif
#ifdef BLKGETNRZONES
	V64(BLKGETNRZONES);
#endif
#ifdef BLKOPENZONE
	V64(BLKOPENZONE);
#endif
#ifdef BLKCLOSEZONE
	V64(BLKCLOSEZONE);
#endif
#ifdef BLKFINISHZONE
	V64(BLKFINISHZONE);
#endif

	seperator();

	V32(SCSI_IOCTL_GET_IDLUN);
	V32(SCSI_IOCTL_TAGGED_ENABLE);
	V32(SCSI_IOCTL_TAGGED_DISABLE);
	V32(SCSI_IOCTL_PROBE_HOST);
	V32(SCSI_IOCTL_GET_BUS_NUMBER);
	V32(SCSI_IOCTL_SEND_COMMAND);
	V32(SCSI_IOCTL_TEST_UNIT_READY);
	V32(SCSI_IOCTL_BENCHMARK_COMMAND);
	V32(SCSI_IOCTL_SYNC);
	V32(SCSI_IOCTL_START_UNIT);
	V32(SCSI_IOCTL_STOP_UNIT);
	V32(SCSI_IOCTL_DOORLOCK);
	V32(SCSI_IOCTL_DOORUNLOCK);

	seperator();

	V32(SG_IO);
	V32(SG_GET_VERSION_NUM);

	seperator();

	V64(FS_IOC_GETFLAGS);
	V64(FS_IOC_SETFLAGS);
	V64(FS_IOC_GETVERSION);
	V64(FS_IOC_SETVERSION);
	V64(FS_IOC_FIEMAP);
	V64(FS_IOC32_GETFLAGS);
	V64(FS_IOC32_SETFLAGS);
	V64(FS_IOC32_GETVERSION);
	V64(FS_IOC32_SETVERSION);
	V64(FS_IOC_FSGETXATTR);
	V64(FS_IOC_FSSETXATTR);
	V64(FS_IOC_GETFSLABEL);
	V64(FS_IOC_SETFSLABEL);

	seperator();

	V32(NVME_IOCTL_ID);
	V64(NVME_IOCTL_ADMIN_CMD);
	V64(NVME_IOCTL_SUBMIT_IO);
	V64(NVME_IOCTL_IO_CMD);
	V32(NVME_IOCTL_RESET);
	V32(NVME_IOCTL_SUBSYS_RESET);
	V32(NVME_IOCTL_RESCAN);
#ifdef NVME_IOCTL_ADMIN64_CMD
	V64(NVME_IOCTL_ADMIN64_CMD);
#endif
#ifdef NVME_IOCTL_IO64_CMD
	V64(NVME_IOCTL_IO64_CMD);
#endif
#undef V32
#undef V64

	reset();
	return 0;
}

